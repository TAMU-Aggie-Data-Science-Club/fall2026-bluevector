"""Frozen Red Sea-evaluation GNN transfer to observed 2026 Hormuz transits.

Run from repository root: python -m scripts.gnn.evaluate_hormuz_transfer
No fitting, checkpoint selection, closure masks, or scenario inference is performed.
The first four affected Friday-ending weeks are reported separately from later weeks.
All outputs remain under ignored data/processed/.
"""
from __future__ import annotations

import hashlib
import json

import numpy as np
import pandas as pd
import torch

from scripts.gnn.evaluate_gnn import metrics
from scripts.gnn.gnn_model import EdgeGNN
from scripts.gnn.train_gnn import OUT, graph_inputs, make_temporal, weekly_counts

START = pd.Timestamp('2026-03-06')
ONSET_END = pd.Timestamp('2026-03-27')
END = pd.Timestamp('2026-11-13')
SEEDS = [7, 19, 43]
MODES = ['real_only', 'simulated_plus_real']


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    torch.set_num_threads(2)
    edges, nodes, edge_index = graph_inputs()
    counts = weekly_counts(edges)
    (_, _, _, history), scales, lag, seasonal = make_temporal(
        edges, nodes, edge_index, counts, 'red_sea_2024')
    locations = np.flatnonzero(edges.searoute_passage.eq('ormuz'))
    if len(locations) != 1:
        raise ValueError('Expected exactly one Hormuz edge')
    index = int(locations[0])
    selected = []
    for sample in history:
        date = pd.Timestamp(sample['scenario_id'])
        if START <= date <= END and bool(sample['loss_mask'][index, 1]):
            selected.append((date, sample))
    expected = pd.date_range(START, END, freq='W-FRI')
    dates = pd.DatetimeIndex([date for date, _ in selected])
    if not dates.equals(expected):
        raise ValueError('Missing complete Hormuz evaluation weeks; do not silently change the sample')
    rows, checkpoints = [], []
    for mode in MODES:
        for seed in SEEDS:
            path = OUT / f'gnn_{mode}_red_sea_2024_seed{seed}.pt'
            before = digest(path)
            # Only load the trusted local checkpoints generated by this project.
            checkpoint = torch.load(path, map_location='cpu', weights_only=False)
            saved_scales = np.asarray(checkpoint['transit_scale'])
            if checkpoint['edge_ids'] != edges.edge_id.tolist():
                raise ValueError('Checkpoint edge order differs from the reference graph')
            # Existing feature construction must exactly reproduce the saved training scale.
            # No target-period observations are used to fit or update normalization.
            if not np.array_equal(scales, saved_scales):
                raise ValueError('Training-scale mismatch; recover original inputs rather than refit')
            model = EdgeGNN(edge_in=14, hidden=32)
            model.load_state_dict(checkpoint['state_dict'])
            model.eval()
            with torch.inference_mode():
                for date, sample in selected:
                    assert sample['x_edge'][:, 7].eq(1).all(), 'Do not force a closure answer'
                    pred, _ = model(sample['x_node'], sample['x_edge'], edge_index)
                    value = float(pred[index, 1]) * float(saved_scales[index])
                    if not np.isfinite(value) or value < 0:
                        raise ValueError('Invalid forecast')
                    rows.append(dict(model=mode, seed=seed, week_ending=date,
                                     edge_id=edges.edge_id.iloc[index],
                                     actual=float(counts.loc[date].iloc[index]), prediction=value,
                                     persistence=float(lag.loc[date].iloc[index]),
                                     seasonal=float(seasonal.loc[date].iloc[index]), source='gnn'))
            if digest(path) != before:
                raise AssertionError('Checkpoint changed during inference')
            checkpoints.append(dict(file=path.name, sha256=before, model=mode, seed=seed,
                                    hormuz_training_scale=float(saved_scales[index])))
    raw = pd.DataFrame(rows)
    ensemble = raw.groupby(['model', 'week_ending', 'edge_id'], as_index=False)[
        ['actual', 'prediction', 'persistence', 'seasonal']].mean()
    baseline = ensemble[ensemble.model.eq('real_only')]
    baseline_rows = []
    for name in ['persistence', 'seasonal']:
        b = baseline.copy()
        b['model'] = name
        b['prediction'] = b[name]
        baseline_rows.append(b)
    forecasts = pd.concat([ensemble] + baseline_rows, ignore_index=True)
    forecasts['source'] = np.where(forecasts.model.isin(MODES), 'gnn', 'modeled')
    scores, per_seed = [], []
    for period in ['all', 'onset', 'later']:
        def window(frame):
            if period == 'onset':
                return frame[frame.week_ending <= ONSET_END]
            if period == 'later':
                return frame[frame.week_ending > ONSET_END]
            return frame
        for name, frame in forecasts.groupby('model'):
            g = window(frame)
            score = metrics(g.actual, g.prediction, g.persistence)
            score['wape'] = float(np.abs(g.prediction - g.actual).sum() / np.abs(g.actual).sum())
            score['mean_actual'] = float(g.actual.mean())
            score['mean_prediction'] = float(g.prediction.mean())
            scores.append(dict(period=period, model=name, source=g.source.iloc[0], **score))
        for (name, seed), frame in raw.groupby(['model', 'seed']):
            g = window(frame)
            per_seed.append(dict(period=period, model=name, seed=seed, source='gnn',
                                 **metrics(g.actual, g.prediction, g.persistence)))
    report = pd.DataFrame(scores)
    benchmark = report[report.model.eq('persistence')].set_index('period').rmse
    report['rmse_skill_vs_persistence'] = 1 - report.rmse / report.period.map(benchmark)
    raw.to_parquet(OUT / 'hormuz_transfer_seed_predictions.parquet', index=False)
    forecasts.to_csv(OUT / 'hormuz_transfer_weekly_predictions.csv', index=False)
    report.to_csv(OUT / 'hormuz_transfer_report.csv', index=False)
    pd.DataFrame(per_seed).to_csv(OUT / 'hormuz_transfer_seed_report.csv', index=False)
    manifest = dict(source='modeled', task='frozen observed-traffic forecast transfer, not closure simulation',
                    test_start=str(START.date()), onset_end=str(ONSET_END.date()), test_end=str(END.date()),
                    seeds=SEEDS, checkpoints=checkpoints, normalization='saved training scales, exact reconstruction checked',
                    selected_after_viewing_errors=False,
                    limitations=['retrospective data revisions/publication lag', 'diagnostic windows declared before this run',
                                 'mixed simulator prior retrospective', 'one-week rolling inputs; no pre-crisis whole-event forecast'])
    (OUT / 'hormuz_transfer_manifest.json').write_text(json.dumps(manifest, indent=2), encoding='utf-8')
    print(report[['period', 'model', 'n', 'mae', 'rmse', 'mape', 'wape',
                  'direction_accuracy', 'mean_actual', 'mean_prediction',
                  'rmse_skill_vs_persistence']].to_string(index=False))
    print('\nFirst four weeks:')
    print(forecasts[forecasts.week_ending <= ONSET_END][
        ['week_ending', 'model', 'actual', 'prediction']].to_string(index=False))


if __name__ == '__main__':
    main()
